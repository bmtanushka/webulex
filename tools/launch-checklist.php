<?php
declare(strict_types=1);

// Local-only: writes LAUNCH_CHECKLIST.md at the project root.
// It combines the fixed go-live checks with every TODO(owner) and REVIEW(owner) marker found in the code,
// so the list always matches the files. Re-run after editing content: php tools/launch-checklist.php

$root = dirname(__DIR__);
$scan = [$root . '/public_html', $root . '/config.sample.php'];
$skip = ['/vendor/', '/node_modules/', '/assets/css/site.css'];
$markers = ['TODO(owner)' => [], 'REVIEW(owner)' => []];

$files = [];
foreach ($scan as $path) {
    if (is_file($path)) {
        $files[] = $path;
        continue;
    }
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS));
    foreach ($it as $f) {
        $p = $f->getPathname();
        if (preg_match('/\.(php|md|js|css)$/', $p)) {
            $files[] = $p;
        }
    }
}
sort($files);
foreach ($files as $file) {
    foreach ($skip as $s) {
        if (str_contains($file, $s)) {
            continue 2;
        }
    }
    $lines = file($file) ?: [];
    foreach ($lines as $n => $line) {
        foreach (array_keys($markers) as $m) {
            if (str_contains($line, $m)) {
                $clean = static fn(string $l): string => trim((string) preg_replace(['~^\s*(//|\*|/\*\*?|<!--|<\?php\s*/\*|\#)\s*~', '~\s*(\*/|-->|\?>)\s*$~'], '', trim($l)));
                $text = $clean($line);
                if (trim(str_replace([$m, ':'], '', $text)) === '' && isset($lines[$n + 1])) {
                    $text .= ' ' . $clean($lines[$n + 1]);
                }
                $text = preg_replace('/\s+/', ' ', $text) ?? $text;
                $markers[$m][] = sprintf('`%s:%d` %s', substr($file, strlen($root) + 1), $n + 1, mb_strimwidth($text, 0, 170, '…'));
            }
        }
    }
}

$md = <<<MD
# Launch checklist

Generated by `php tools/launch-checklist.php` on {date}. Re-run it after editing content.
For owner decisions and accounts, see **TODO.md**; this file is the technical go-live list plus every marker left in the code.

## 1. Before deploying

- [ ] `php tools/build-css.php` (rebuild `assets/css/site.css`)
- [ ] `php tools/launch-checklist.php` (refresh this file)
- [ ] All tests pass locally: `NODE_PATH=tools/node_modules node tests/smoke.cjs` and `tests/forms.cjs` (forms need `FORM_TEST_MODE => true`)
- [ ] `php -l` passes on every PHP file
- [ ] `config.php` is **not** in the upload and real secrets are only on the server
- [ ] `FORM_TEST_MODE` is `false` and `DEV` is `false` in the server's `config.php`
- [ ] `SHOW_DRAFTS` is `false` on the server

## 2. Server setup (Hostinger, once)

- [ ] Domain points to Hostinger; free SSL active
- [ ] PHP 8.2+ with `curl`, `mbstring`, `openssl`, `fileinfo`
- [ ] `config.php` uploaded one level above `public_html` (e.g. `/home/USER/domains/webulexpro.com/config.php`)
- [ ] `storage/logs/` exists one level above `public_html` and is writable by PHP
- [ ] Mailbox `info@webulexpro.com` created; SMTP details in `config.php`

## 3. Live checks after every deploy (BRIEF §13.5)

- [ ] `https://webulexpro.com` loads with a valid certificate
- [ ] `http://` and `https://www.` redirect to `https://webulexpro.com`
- [ ] 200: `/`, `/services/seo`, `/packages/complete-business-launch`, `/industries/cleaning-companies`, `/blog`, `/sitemap.xml`, `/robots.txt`, `/llms.txt`
- [ ] 404: a made-up URL such as `/this-does-not-exist`
- [ ] 403: `/app/`, `/content/`, `/templates/`, `/vendor/`
- [ ] Response headers on `/` include `Content-Security-Policy`, `Strict-Transport-Security`, `X-Content-Type-Options`
- [ ] Browser console on `/`, `/contact` and a service page shows no CSP errors (with GA accepted)
- [ ] A real test lead reaches n8n **and** the inbox, and the confirmation email arrives
- [ ] Lighthouse (mobile) on the live home page: record the four scores
- [ ] Submit `https://webulexpro.com/sitemap.xml` in Google Search Console

## 4. Owner markers in the code ({todo_count} TODO, {review_count} REVIEW)

### TODO(owner): information or decisions needed

{todos}

### REVIEW(owner): drafted text to check

{reviews}
MD;

$list = static fn(array $items): string => $items ? implode("\n", array_map(static fn(string $i): string => '- [ ] ' . $i, $items)) : '_None._';
$md = strtr($md, [
    '{date}' => date('j F Y'),
    '{todo_count}' => (string) count($markers['TODO(owner)']),
    '{review_count}' => (string) count($markers['REVIEW(owner)']),
    '{todos}' => $list($markers['TODO(owner)']),
    '{reviews}' => $list($markers['REVIEW(owner)']),
]);
file_put_contents($root . '/LAUNCH_CHECKLIST.md', $md);
printf("LAUNCH_CHECKLIST.md: %d TODO, %d REVIEW markers\n", count($markers['TODO(owner)']), count($markers['REVIEW(owner)']));
