<?php
declare(strict_types=1);

// Local-only: copies the Lucide icons the site uses (ISC licence) into
// public_html/templates/partials/icons.php as inline SVG snippets.
// Run: php tools/make-icons.php   (after `npm install` in tools/)

$names = [
    'arrow-right', 'arrow-up-right', 'bot', 'brush', 'building-2', 'calendar-check', 'calendar-days',
    'chart-column', 'chart-line', 'check', 'chevron-down', 'circle-check', 'clock', 'code', 'compass',
    'cpu', 'credit-card', 'file-text', 'gauge', 'globe', 'handshake', 'image', 'inbox', 'layers',
    'layout-template', 'lightbulb', 'mail', 'map-pin', 'megaphone', 'menu', 'message-circle',
    'message-square', 'mouse-pointer-click', 'palette', 'phone', 'phone-call', 'plug', 'rocket',
    'search', 'send', 'server', 'share-2', 'shield-check', 'shopping-cart', 'sparkles', 'star',
    'target', 'trending-up', 'user', 'users', 'video', 'workflow', 'wrench', 'x', 'zap', 'at-sign',
    'briefcase', 'circle-play', 'refresh-cw', 'receipt', 'lock', 'smartphone', 'bell',
];

$dir = __DIR__ . '/node_modules/lucide-static/icons/';
$out = [];
foreach ($names as $name) {
    $file = $dir . $name . '.svg';
    if (!is_file($file)) {
        fwrite(STDERR, "missing icon: $name\n");
        continue;
    }
    $svg = (string) file_get_contents($file);
    if (!preg_match('#<svg[^>]*>(.*)</svg>#s', $svg, $m)) {
        continue;
    }
    $inner = preg_replace('/\s+/', ' ', trim($m[1]));
    $out[$name] = str_replace(' />', '/>', (string) $inner);
}

$php = "<?php\ndeclare(strict_types=1);\n\n// Generated by tools/make-icons.php from lucide-static (ISC licence). Do not edit by hand.\n\nreturn " . var_export($out, true) . ";\n";
file_put_contents(__DIR__ . '/../public_html/templates/partials/icons.php', $php);
echo count($out) . " icons written\n";
