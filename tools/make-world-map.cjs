// Local-only: generates the dotted world map SVGs used in the hero and About page.
// Run: node tools/make-world-map.cjs   (from the project root)
// Output: public_html/assets/img/world-dots-dark.svg and world-dots-light.svg
'use strict';
const fs = require('fs');
const path = require('path');
const DottedMap = require('dotted-map').default;

const map = new DottedMap({
  height: 64,
  grid: 'diagonal',
  region: { lat: { min: -50, max: 72 }, lng: { min: -170, max: 180 } },
});

const markets = [
  { id: 'us', lat: 39.5, lng: -98.35 },
  { id: 'uk', lat: 52.6, lng: -1.5 },
  { id: 'sg', lat: 1.35, lng: 103.82 },
  { id: 'au', lat: -27.5, lng: 135.0 },
];
const home = { id: 'lk', lat: 7.9, lng: 80.7 };

const pts = map.getPoints();
const W = map.image.width;
const H = map.image.height;
const r1 = (n) => Math.round(n * 10) / 10;

const pin = (p) => {
  const found = map.getPin({ lat: p.lat, lng: p.lng });
  return { ...p, x: r1(found.x), y: r1(found.y) };
};
const mk = markets.map(pin);
const lk = pin(home);

function arc(a, b) {
  const mx = (a.x + b.x) / 2;
  const my = (a.y + b.y) / 2;
  const dist = Math.hypot(b.x - a.x, b.y - a.y);
  const cy = my - dist * 0.35;
  return `M${a.x} ${a.y}Q${r1(mx)} ${r1(cy)} ${b.x} ${b.y}`;
}

function build(theme) {
  const dot = theme === 'dark' ? 'rgba(255,255,255,.22)' : 'rgba(48,63,159,.3)';
  const arcCol = theme === 'dark' ? 'rgba(41,182,246,.75)' : 'rgba(48,63,159,.55)';
  const r = 0.36;
  // Each dot is a zero-length line with a round cap: ~12 bytes per dot.
  const d = pts.map((p) => `M${r1(p.x)} ${r1(p.y)}h0`).join('');
  const pinsSvg = mk
    .map(
      (p, i) =>
        `<g class="pin" style="animation-delay:${i * 0.6}s"><circle class="halo" cx="${p.x}" cy="${p.y}" r="1.6" fill="#29B6F6"/><circle cx="${p.x}" cy="${p.y}" r="0.9" fill="#29B6F6"/></g>`
    )
    .join('');
  const arcs = mk.map((p) => `<path class="arc" d="${arc(lk, p)}"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r1(W)} ${r1(H)}" preserveAspectRatio="xMidYMid meet">
<style>
.arc{fill:none;stroke:${arcCol};stroke-width:.25;stroke-dasharray:1 1;stroke-linecap:round;animation:dash 6s linear infinite}
.halo{opacity:.35;transform-box:fill-box;transform-origin:center;animation:pulse 3s ease-out infinite}
.lk .halo{fill:#D946EF}
@keyframes dash{to{stroke-dashoffset:-20}}
@keyframes pulse{0%{transform:scale(.6);opacity:.55}100%{transform:scale(2.2);opacity:0}}
@media (prefers-reduced-motion:reduce){.arc,.halo{animation:none}}
</style>
<path d="${d}" stroke="${dot}" stroke-width="${r * 2}" stroke-linecap="round"/>
${arcs}
${pinsSvg}
<g class="pin lk"><circle class="halo" cx="${lk.x}" cy="${lk.y}" r="1.8"/><circle cx="${lk.x}" cy="${lk.y}" r="1" fill="#D946EF"/></g>
</svg>
`;
}

const out = path.join(__dirname, '..', 'public_html', 'assets', 'img');
fs.mkdirSync(out, { recursive: true });
for (const t of ['dark', 'light']) {
  const file = path.join(out, `world-dots-${t}.svg`);
  fs.writeFileSync(file, build(t));
  console.log(file, (fs.statSync(file).size / 1024).toFixed(1) + ' KB', pts.length + ' dots');
}

// Hero version: dots as a mask image (not a paint candidate, so it never delays first paint)
// plus an inline SVG partial with just the pins and arcs, sharing the same viewBox.
{
  const r = 0.36;
  const d = pts.map((p) => `M${r1(p.x)} ${r1(p.y)}h0`).join('');
  const mask = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r1(W)} ${r1(H)}"><path d="${d}" stroke="#000" stroke-width="${r * 2}" stroke-linecap="round"/></svg>\n`;
  fs.writeFileSync(path.join(out, 'world-dots-mask.svg'), mask);
  const full = build('dark');
  const overlay = full
    .replace(/<path d="[^"]*" stroke="[^"]*" stroke-width="[^"]*" stroke-linecap="round"\/>\n/, '')
    .replace('<svg xmlns="http://www.w3.org/2000/svg"', '<svg xmlns="http://www.w3.org/2000/svg" class="hero__pins" aria-hidden="true" focusable="false"')
    // Inline on the page, so prefix class and animation names to keep them from clashing.
    .replace(/\b(arc|halo|pin|lk|dash|pulse)\b/g, 'wm-$1');
  const partial = path.join(__dirname, '..', 'public_html', 'templates', 'partials', 'world-pins.php');
  fs.writeFileSync(partial, `<?php\ndeclare(strict_types=1);\n// Generated by tools/make-world-map.cjs. Do not edit by hand.\n?>\n${overlay}`);
  console.log('world-dots-mask.svg + world-pins.php', (overlay.length / 1024).toFixed(1) + ' KB inline');
}
