<?php
declare(strict_types=1);

/** Escape for HTML output. Use on every dynamic value. */
function e(string|int|float|null $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/** Read a config value from ../config.php. */
function config(string $key, mixed $default = null): mixed
{
    return $GLOBALS['config'][$key] ?? $default;
}

/** Feature flags (e.g. SHOW_TESTIMONIALS). Off unless config turns them on. */
function feature(string $flag): bool
{
    return (bool) config($flag, false);
}

/** Site content arrays from /content, loaded once per request. */
function content(string $name): array
{
    static $cache = [];
    if (!isset($cache[$name])) {
        $file = APP_ROOT . '/content/' . basename($name) . '.php';
        $cache[$name] = is_file($file) ? (array) require $file : [];
    }
    return $cache[$name];
}

function site(string $key, mixed $default = null): mixed
{
    return content('site')[$key] ?? $default;
}

/** Root-relative URL for an internal path. */
function url(string $path = '/'): string
{
    return '/' . ltrim($path, '/');
}

/** Absolute URL on the canonical host. */
function absolute_url(string $path = '/'): string
{
    return rtrim((string) site('base_url'), '/') . url($path);
}

/** Asset URL with a cache-busting version from the file's modified time. */
function asset(string $path): string
{
    $path = ltrim($path, '/');
    $file = APP_ROOT . '/assets/' . $path;
    $v = is_file($file) ? '?v=' . filemtime($file) : '';
    return '/assets/' . $path . $v;
}

/** Inline Lucide icon. Decorative by default; pass a label to make it meaningful. */
function icon(string $name, string $class = '', ?string $label = null): string
{
    static $icons = null;
    $icons ??= (array) require APP_ROOT . '/templates/partials/icons.php';
    $inner = $icons[$name] ?? '';
    $a11y = $label === null
        ? 'aria-hidden="true" focusable="false"'
        : 'role="img" aria-label="' . e($label) . '"';
    return '<svg class="icon ' . e($class) . '" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ' . $a11y . '>' . $inner . '</svg>';
}

/**
 * Inline an illustration from assets/illustrations/{name}.svg, recoloured to the cyan accent.
 * Missing files render a gradient placeholder so pages never break.
 */
function illustration(string $name, string $alt = '', string $class = ''): string
{
    static $cache = [];
    $name = preg_replace('/[^a-z0-9-]/', '', strtolower($name)) ?? '';
    $file = APP_ROOT . '/assets/illustrations/' . $name . '.svg';
    $classes = trim('illustration ' . $class);

    if (!is_file($file)) {
        $label = $alt !== '' ? 'role="img" aria-label="' . e($alt) . '"' : 'aria-hidden="true"';
        return '<div class="' . e($classes) . ' illustration--placeholder" ' . $label . '><span></span><span></span><span></span></div>';
    }

    if (!isset($cache[$name])) {
        $svg = (string) file_get_contents($file);
        $svg = preg_replace('/<\?xml.*?\?>/s', '', $svg) ?? $svg;
        $svg = preg_replace('/<!--.*?-->/s', '', $svg) ?? $svg;
        $svg = str_ireplace(['#6c63ff', '#6C63FF'], 'currentColor', $svg);
        // Drop fixed sizes so CSS controls the size.
        $svg = preg_replace('/(<svg\b[^>]*?)\s(width|height)="[^"]*"/i', '$1', $svg) ?? $svg;
        $svg = preg_replace('/(<svg\b[^>]*?)\s(width|height)="[^"]*"/i', '$1', $svg) ?? $svg;
        $svg = preg_replace('/<title>.*?<\/title>/s', '', $svg) ?? $svg;
        $cache[$name] = trim($svg);
    }

    $svg = $cache[$name];
    $id = 'ill-' . $name . '-' . substr(md5($alt . $class), 0, 6);
    if ($alt !== '') {
        $svg = preg_replace('/<svg\b/', '<svg role="img" aria-labelledby="' . $id . '"', $svg, 1) ?? $svg;
        $svg = preg_replace('/(<svg\b[^>]*>)/', '$1<title id="' . $id . '">' . e($alt) . '</title>', $svg, 1) ?? $svg;
    } else {
        $svg = preg_replace('/<svg\b/', '<svg aria-hidden="true" focusable="false"', $svg, 1) ?? $svg;
    }
    return '<div class="' . e($classes) . '">' . $svg . '</div>';
}

/** The Webulex logo (generated by tools/make-logo.py). 'light' is for dark backgrounds. */
function logo(string $variant = 'dark'): string
{
    $file = $variant === 'light' ? 'webulex-logo-light.svg' : 'webulex-logo.svg';
    if (is_file(APP_ROOT . '/assets/brand/' . $file)) {
        return '<img src="' . e(asset('brand/' . $file)) . '" alt="Webulex" width="160" height="36" class="logo__img">';
    }
    return '<span class="logo__text">Webulex</span>';
}

/** WhatsApp link with a pre-filled message naming the page. */
function whatsapp_url(string $pageName = ''): string
{
    $text = 'Hello Webulex, I would like to talk about my project.';
    if ($pageName !== '') {
        $text .= ' (From the ' . $pageName . ' page)';
    }
    return 'https://wa.me/' . site('whatsapp_number') . '?text=' . rawurlencode($text);
}

/** Render a template file with the given variables. */
function render(string $template, array $vars = []): string
{
    $file = APP_ROOT . '/templates/' . $template . '.php';
    if (!is_file($file)) {
        throw new RuntimeException('Template not found: ' . $template);
    }
    extract($vars, EXTR_SKIP);
    ob_start();
    require $file;
    return (string) ob_get_clean();
}

/** Include a partial (templates/partials/{name}.php) with data. */
function partial(string $name, array $vars = []): string
{
    return render('partials/' . $name, $vars);
}

function current_path(): string
{
    $path = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH);
    $path = is_string($path) ? rawurldecode($path) : '/';
    $path = '/' . trim($path, '/');
    return $path;
}

function is_current(string $path): bool
{
    $cur = current_path();
    return $path === '/' ? $cur === '/' : ($cur === $path || str_starts_with($cur, rtrim($path, '/') . '/'));
}

/** One service with its drafted details merged in, or null. */
function service(string $slug): ?array
{
    $base = content('services')['services'][$slug] ?? null;
    if ($base === null) {
        return null;
    }
    $details = content('service-details');
    $s = $base + ($details['services'][$slug] ?? []) + ['slug' => $slug];
    $s['process'] ??= $details['areas'][$s['area']]['process'] ?? [];
    $s['outcomes'] ??= [];
    $s['faqs'] ??= [];
    return $s;
}

/** @return array<string,array> services in one area, keyed by slug */
function services_in_area(string $area): array
{
    return array_filter(content('services')['services'], static fn(array $s): bool => $s['area'] === $area);
}

/**
 * Packages (general and industry) that include any of the given services.
 * @param string[] $serviceSlugs
 * @return array<int,array{title:string,url:string,meta:string,type:string}>
 */
function packages_including(array $serviceSlugs): array
{
    $out = [];
    foreach (content('packages') as $slug => $p) {
        if (array_intersect($serviceSlugs, $p['services'] ?? [])) {
            $out[] = ['title' => $p['title'], 'url' => '/packages/' . $slug, 'meta' => $p['timeline'], 'type' => !empty($p['flagship']) ? 'Flagship package' : 'Package', 'text' => $p['tagline']];
        }
    }
    foreach (content('industries') as $slug => $i) {
        if (array_intersect($serviceSlugs, $i['services'] ?? [])) {
            $out[] = ['title' => 'Packages for ' . lcfirst($i['title']), 'url' => '/industries/' . $slug, 'meta' => '3 tiers', 'type' => 'By business type', 'text' => implode(' ', $i['headline'])];
        }
    }
    return $out;
}

/** "a, b and c" */
function human_list(array $items): string
{
    $items = array_values($items);
    if (count($items) < 2) {
        return (string) ($items[0] ?? '');
    }
    $last = array_pop($items);
    return implode(', ', $items) . ' and ' . $last;
}

/** BreadcrumbList schema plus visible breadcrumb data. @param array<int,array{0:string,1:string}> $trail [label, path] */
function breadcrumb_schema(array $trail): array
{
    return [
        '@context' => 'https://schema.org',
        '@type' => 'BreadcrumbList',
        'itemListElement' => array_map(static fn(array $t, int $i): array => [
            '@type' => 'ListItem', 'position' => $i + 1, 'name' => $t[0], 'item' => absolute_url($t[1]),
        ], $trail, array_keys($trail)),
    ];
}

/**
 * Price label for a package. Shows "Price on request" until the owner adds prices and turns on SHOW_PRICES.
 * TODO(owner): prices.
 */
function package_price(array $p): string
{
    if (feature('SHOW_PRICES') && !empty($p['prices'])) {
        $symbols = ['USD' => 'US$', 'GBP' => '£', 'SGD' => 'S$', 'AUD' => 'A$'];
        $parts = [];
        foreach ($p['prices'] as $cur => $amount) {
            $parts[] = ($symbols[$cur] ?? $cur . ' ') . number_format((float) $amount);
        }
        return 'From ' . implode(' · ', $parts);
    }
    return 'Price on request';
}

/** Comparison rows for industry tiers: each item with the tier index it first appears in. */
function tier_rows(array $tiers): array
{
    $rows = [];
    foreach ($tiers as $i => $t) {
        foreach ($t['items'] as $item) {
            $rows[] = ['item' => $item, 'from' => $i];
        }
    }
    return $rows;
}
